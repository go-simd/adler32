// Package fletcher4 is the ZFS fletcher4 block checksum with SIMD kernels.
//
// fletcher4 reads a buffer as little-endian 32-bit words w and keeps four 64-bit
// running sums, all mod 2^64:
//
//	a += w; b += a; c += b; d += c
//
// Sum returns [4]uint64{a, b, c, d} for the "native" (little-endian) form: the
// exact value of OpenZFS fletcher_4_native (module/zcommon/zfs_fletcher.c,
// fletcher_4_scalar_native), which is what ZFS stores in a block pointer's
// blk_cksum on a little-endian pool. A trailing partial word (len(buf) % 4 != 0)
// is ignored, as OpenZFS requires whole words.
//
// The SIMD kernels (AVX2 and AVX-512 on amd64, NEON on arm64; generated by
// go-asmgen, see internal/gen) keep L independent lanes, lane j summing the
// words j, j+L, j+2L, ..., and the lanes are folded with the same closed forms
// OpenZFS uses in its fini functions (zfs_fletcher_intel.c, _avx512.c,
// _aarch64_neon.c). The result is bit-identical to the scalar loop on every
// input; other architectures use the scalar loop.
package fletcher4

import (
	"encoding/binary"
	"math/big"
)

// simd describes the widest kernel the running CPU can use; run == nil means
// scalar. It is set once by the per-architecture init.
var simd struct {
	name       string
	lanes      int // L: independent lanes (2, 4 or 8)
	blockBytes int // bytes consumed per unit of the kernel's block count (a power of two)
	run        func(p *byte, nblocks int, out *[32]uint64)
}

// Implementation names the kernel Sum uses on this machine ("scalar" when none).
func Implementation() string {
	if simd.run == nil {
		return "scalar"
	}
	return simd.name
}

// Sum returns the fletcher4 checksum of buf.
func Sum(buf []byte) [4]uint64 {
	buf = buf[:len(buf)&^3]
	if simd.run == nil || len(buf) < 2*simd.blockBytes {
		return SumScalar(buf)
	}
	return sumWith(buf, simd.lanes, simd.blockBytes, simd.run)
}

// SumScalar is the plain loop: the reference every kernel must equal.
func SumScalar(buf []byte) [4]uint64 {
	a, b, c, d := scalar(0, 0, 0, 0, buf)
	return [4]uint64{a, b, c, d}
}

func scalar(a, b, c, d uint64, buf []byte) (uint64, uint64, uint64, uint64) {
	for i := 0; i+4 <= len(buf); i += 4 {
		a += uint64(binary.LittleEndian.Uint32(buf[i:]))
		b += a
		c += b
		d += c
	}
	return a, b, c, d
}

// sumWith folds the kernel's blocks, then continues the scalar loop from the
// folded state over the remaining words. A state (a, b, c, d) is all the scalar
// loop needs, so no further correction is required for the tail.
func sumWith(buf []byte, lanes, blockBytes int, run func(*byte, int, *[32]uint64)) [4]uint64 {
	n := len(buf) &^ (blockBytes - 1)
	var out [32]uint64
	run(&buf[0], n/blockBytes, &out)
	st := fold(lanes, &out)
	a, b, c, d := scalar(st[0], st[1], st[2], st[3], buf[n:])
	return [4]uint64{a, b, c, d}
}

// fold combines per-lane accumulators out[g*L+j] (g = a, b, c, d; j = lane) of a
// run over a whole number of L-word groups into the fletcher4 state.
//
// With N = L*n words, lane j holds, for its element t places from the end of the
// lane (t = 1 for the last), the weights 1, t, C(t+1,2), C(t+2,3) on (a, b, c,
// d); globally that element is s = L*t - j words from the end and weighs 1, s,
// C(s+1,2), C(s+2,3). Each global weight is a cubic in t, so it is a fixed
// integer combination of the lane weights; coefs holds those integers (solved
// exactly in init, equal to the constants of OpenZFS's fini functions).
func fold(L int, out *[32]uint64) [4]uint64 {
	cf := coefs[L]
	var r [4]uint64
	for o := 0; o < 4; o++ {
		var sum uint64
		for j := 0; j < L; j++ {
			for k := 0; k < 4; k++ {
				sum += cf[o][j][k] * out[k*L+j]
			}
		}
		r[o] = sum
	}
	return r
}

// coefs[L][o][j][k]: coefficient (mod 2^64) of lane j's accumulator k in global
// output o.
var coefs = map[int]*[4][8][4]uint64{}

func init() {
	for _, L := range []int{2, 4, 8} {
		coefs[L] = solveCoefs(L)
	}
}

// binom(n, k) for the small k used here.
func binom(n int64, k int) *big.Rat {
	r := big.NewRat(1, 1)
	for i := 0; i < k; i++ {
		r.Mul(r, big.NewRat(n-int64(i), int64(i+1)))
	}
	return r
}

func solveCoefs(L int) *[4][8][4]uint64 {
	var res [4][8][4]uint64
	for j := 0; j < L; j++ {
		for o := 0; o < 4; o++ {
			// Rows t = 1..4: basis[t] = {1, t, C(t+1,2), C(t+2,3)}; rhs = global
			// weight at s = L*t - j.
			var m [4][5]*big.Rat
			for i := 0; i < 4; i++ {
				t := int64(i + 1)
				s := int64(L)*t - int64(j)
				row := [4]*big.Rat{binom(0, 0), big.NewRat(t, 1), binom(t+1, 2), binom(t+2, 3)}
				for k := 0; k < 4; k++ {
					m[i][k] = row[k]
				}
				var w *big.Rat
				switch o {
				case 0:
					w = big.NewRat(1, 1)
				case 1:
					w = big.NewRat(s, 1)
				case 2:
					w = binom(s+1, 2)
				default:
					w = binom(s+2, 3)
				}
				m[i][4] = w
			}
			x := gauss(m)
			for k := 0; k < 4; k++ {
				if !x[k].IsInt() {
					panic("fletcher4: non-integer fold coefficient")
				}
				v := x[k].Num()
				res[o][j][k] = uint64(v.Int64()) // two's complement: mod 2^64
			}
		}
	}
	return &res
}

// gauss solves the 4x4 system in m (augmented) exactly.
func gauss(m [4][5]*big.Rat) [4]*big.Rat {
	for c := 0; c < 4; c++ {
		p := c
		for p < 4 && m[p][c].Sign() == 0 {
			p++
		}
		m[c], m[p] = m[p], m[c]
		inv := new(big.Rat).Inv(m[c][c])
		for k := c; k < 5; k++ {
			m[c][k] = new(big.Rat).Mul(m[c][k], inv)
		}
		for r := 0; r < 4; r++ {
			if r == c || m[r][c].Sign() == 0 {
				continue
			}
			f := new(big.Rat).Set(m[r][c])
			for k := c; k < 5; k++ {
				m[r][k] = new(big.Rat).Sub(m[r][k], new(big.Rat).Mul(f, m[c][k]))
			}
		}
	}
	return [4]*big.Rat{m[0][4], m[1][4], m[2][4], m[3][4]}
}
